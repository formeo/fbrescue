#!/usr/bin/env bash
# Generates internal/value/timezones_gen.go: Firebird's time zone ids and
# names from RDB$TIME_ZONES, using an engine installed by tools/mkcorpus.
# Usage: tools/gentimezones/gen.sh [engine version, default 50] > internal/value/timezones_gen.go
set -euo pipefail
v=${1:-50}
fb=$(cd "$(dirname "$0")/../mkcorpus" && pwd)/fb.sh
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
echo "create database '$tmp/tz.fdb'; quit;" | "$fb" "$v" isql -q
echo "Code generated by tools/gentimezones/gen.sh from Firebird $v RDB\$TIME_ZONES; DO NOT EDIT." | sed 's|^|// |'
echo
echo "package value"
echo
echo "var timeZones = map[uint16]string{"
echo "set heading off; select '	' || rdb\$time_zone_id || ': \"' || trim(rdb\$time_zone_name) || '\",' from rdb\$time_zones order by rdb\$time_zone_id desc; quit;" |
  "$fb" "$v" isql -q "$tmp/tz.fdb" | grep -v '^$' | sed 's/ *$//'
echo "}"
