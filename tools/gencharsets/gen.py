def high_half(codec):
    out = []
    for b in range(0x80, 0x100):
        try:
            s = bytes([b]).decode(codec)
            out.append(ord(s) if len(s) == 1 else 0xFFFD)
        except UnicodeDecodeError:
            out.append(0xFFFD)
    return out

